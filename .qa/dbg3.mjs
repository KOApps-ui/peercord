import { chromium } from 'playwright'
const b = await chromium.launch(); const p = await b.newPage({ viewport:{width:1440,height:900} })
p.on('console', m => { if (m.type()==='error') console.log('C:', m.text().slice(0,180)) })
p.on('pageerror', e => console.log('PE:', e.message.slice(0,180)))
await p.goto('http://localhost:5180/', {waitUntil:'domcontentloaded'}); await p.waitForTimeout(1200)
await p.getByRole('button', { name: 'Sunucu Oluştur' }).first().click(); await p.waitForTimeout(400)
const d = p.locator('[role="dialog"]')
await d.getByLabel('Sunucu adı').fill('Enter Testi'); await p.waitForTimeout(400)
await d.getByRole('button', { name: 'Sunucu Oluştur' }).click(); await p.waitForTimeout(2500)
const ta = p.locator('textarea').first()
await ta.click(); await ta.fill('deneme')
console.log('filled, value=', await ta.inputValue())
const enabled = await ta.isEnabled(); const visible = await ta.isVisible()
console.log('enabled', enabled, 'visible', visible)
await p.keyboard.press('Enter')
await p.waitForTimeout(1500)
console.log('state msgs:', await p.evaluate(()=>Object.values(window.__pc.useAppStore.getState().messages).reduce((a,b)=>a+b.length,0)))
await p.screenshot({ path: '/tmp/pc-enter.png' })
await b.close()
