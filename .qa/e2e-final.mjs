import { chromium } from 'playwright'
const b = await chromium.launch()
const A = await b.newContext({ viewport: { width: 1440, height: 900 } })
const B = await b.newContext({ viewport: { width: 1440, height: 900 } })
const pa = await A.newPage(); const pb = await B.newPage()
b.on('disconnected', ()=>console.log('BROWSER DISCONNECTED'))
pa.on('crash', ()=>console.log('A CRASH')); pb.on('crash', ()=>console.log('B CRASH'))
pa.on('close', ()=>console.log('A CLOSE')); pb.on('close', ()=>console.log('B CLOSE'))
const errs = []
for (const [n,p] of [['A',pa],['B',pb]]) { p.on('pageerror', e=>errs.push(n+': '+e.message.slice(0,160))); p.on('console', m=>{ if(m.type()==='error') errs.push(n+' C: '+m.text().slice(0,100)) }) }
const state = (p) => p.evaluate(()=>{const s=window.__pc.useAppStore.getState();return {guild:s.guild?.name??null, msgs:Object.values(s.messages).reduce((a,b)=>a+b.length,0), peers:s.peers.length, members:Object.keys(s.members).length}})
await pa.goto('http://localhost:5180/', {waitUntil:'domcontentloaded'}); await pa.waitForTimeout(1200)
await pa.getByRole('button', { name: 'Sunucu Oluştur' }).first().click(); await pa.waitForTimeout(400)
const d = pa.locator('[role="dialog"]')
await d.getByLabel('Sunucu adı').fill('Gece Kulübü'); await pa.waitForTimeout(500)
await d.getByRole('button', { name: 'Sunucu Oluştur' }).click(); await pa.waitForTimeout(2500)
const url = await pa.evaluate(()=>location.href)
await pb.goto(url, {waitUntil:'domcontentloaded'}); await pb.waitForTimeout(5000)
console.log('A state:', JSON.stringify(await state(pa)))
console.log('B state:', JSON.stringify(await state(pb)))
const ta = pa.locator('textarea').first()
await ta.fill('Selam P2P mesaj'); await pa.waitForTimeout(500)
await pa.keyboard.press('Enter'); await pa.waitForTimeout(2500)
const tb = pb.locator('textarea').first()
await tb.fill('B cevap'); await pb.waitForTimeout(500)
await pb.keyboard.press('Enter'); await pb.waitForTimeout(2500)
console.log('A state2:', JSON.stringify(await state(pa)))
console.log('B state2:', JSON.stringify(await state(pb)))
const t1 = await pa.locator('main').innerText(); const t2 = await pb.locator('main').innerText()
console.log('A gördü:', t1.includes('Selam P2P'), t1.includes('B cevap'))
console.log('B gördü:', t2.includes('Selam P2P'), t2.includes('B cevap'))
console.log('A sidebar:', (await pa.locator('aside').first().innerText()).split('\n').slice(0,4).join(' | '))
console.log('A member panel:', (await pa.locator('aside').last().innerText()).split('\n').slice(0,4).join(' | '))
await pa.screenshot({path:'/tmp/pc-e2e-A.png'}); await pb.screenshot({path:'/tmp/pc-e2e-B.png'})
console.log('ERRS:', JSON.stringify([...new Set(errs)].slice(0,5)))
await b.close()
