import { chromium } from 'playwright'
const b = await chromium.launch()
const p = await b.newPage({ viewport: { width: 1440, height: 900 } })
p.on('pageerror', e => console.log('PE:', e.message))
p.on('console', m => { if (m.type()==='error') console.log('C:', m.text().slice(0,150)) })
await p.goto('http://localhost:5180/', { waitUntil: 'domcontentloaded' })
await p.waitForTimeout(1500)
console.log('1 BODY:', (await p.locator('body').innerText()).slice(0,120).replace(/\n/g,'|'))
await p.getByRole('button', { name: 'Sunucu Oluştur' }).first().click()
await p.waitForTimeout(600)
console.log('2 BODY:', (await p.locator('body').innerText()).slice(0,200).replace(/\n/g,'|'))
await p.screenshot({ path: '/tmp/pc-step2.png' })
const inputs = await p.locator('input').evaluateAll(els => els.map(e => ({ ph: e.placeholder, label: e.getAttribute('aria-label'), id: e.id })))
console.log('INPUTS:', JSON.stringify(inputs))
await p.getByLabel('Sunucu adı').fill('Debug Odası')
await p.waitForTimeout(300)
const btns = await p.getByRole('button').allInnerTexts()
console.log('BUTTONS:', JSON.stringify(btns))
await p.getByRole('button', { name: 'Sunucu Oluştur' }).last().click()
await p.waitForTimeout(2500)
await p.screenshot({ path: '/tmp/pc-step3.png' })
const st = await p.evaluate(() => { const s = window.__pc?.useAppStore?.getState?.(); return s ? { ready:s.ready, guild:s.guild?.name, err:s.error, modal:s.modal } : 'no' })
console.log('STATE:', JSON.stringify(st))
console.log('3 BODY:', (await p.locator('body').innerText()).slice(0,250).replace(/\n/g,'|'))
await b.close()
