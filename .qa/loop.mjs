import { chromium } from 'playwright'
const b = await chromium.launch()
const A = await b.newContext({ viewport: { width: 1440, height: 900 } })
const pa = await A.newPage()
pa.on('console', m => { if (m.type()==='error') console.log('A-C:', m.text().slice(0,140)) })
pa.on('crash', () => console.log('A CRASHED'))
pa.on('pageerror', e => console.log('A-PE:', e.message.slice(0,140)))
await pa.goto('http://localhost:5180/', { waitUntil: 'domcontentloaded' }); await pa.waitForTimeout(1000)
await pa.getByRole('button', { name: 'Sunucu Oluştur' }).first().click(); await pa.waitForTimeout(400)
const d = pa.locator('[role="dialog"]')
await d.getByLabel('Sunucu adı').fill('Loop Testi'); await pa.waitForTimeout(400)
await d.getByRole('button', { name: 'Sunucu Oluştur' }).click(); await pa.waitForTimeout(2500)
console.log('A ok, room:', await pa.evaluate(()=>location.hash))
const url = await pa.evaluate(()=>location.href)
const B = await b.newContext({ viewport: { width: 1440, height: 900 } })
const pb = await B.newPage()
pb.on('console', m => { if (m.type()==='error') console.log('B-C:', m.text().slice(0,140)) })
pb.on('crash', () => console.log('B CRASHED'))
await pb.goto(url, { waitUntil: 'domcontentloaded' })
for (let i=0;i<6;i++) { await pa.waitForTimeout(2000); try { console.log(i*2+'s A alive:', await pa.evaluate(()=>document.readyState)) } catch(e) { console.log('A DEAD', e.message.slice(0,60)); break } }
await b.close()
