import { chromium } from 'playwright'
const b = await chromium.launch()
const A = await b.newContext({ viewport: { width: 1440, height: 900 } })
const B = await b.newContext({ viewport: { width: 1280, height: 800 } })
const pa = await A.newPage(); const pb = await B.newPage()
pa.on('console', m => { if (m.text().includes('[P2P]')) console.log('A>', m.text().slice(0,160)) })
pb.on('console', m => { if (m.text().includes('[P2P]')) console.log('B>', m.text().slice(0,160)) })
await pa.goto('http://localhost:5181/', { waitUntil: 'domcontentloaded' })
await pa.waitForTimeout(1000)
await pa.getByRole('button', { name: 'Sunucu Oluştur' }).first().click()
await pa.waitForTimeout(400)
await pa.getByLabel('Sunucu adı').fill('Test Odası')
await pa.getByRole('button', { name: 'Sunucu Oluştur' }).last().click()
await pa.waitForTimeout(3000)
await pa.keyboard.press('Escape')
await pa.getByRole('button', { name: /Davet/ }).first().click().catch(()=>pa.getByText('Davet et').click())
await pa.waitForTimeout(700)
const inv = await pa.locator('input').evaluateAll(els => els.map(e=>e.value).find(v=>v.includes('#/oda')))
await pa.keyboard.press('Escape')
console.log('ROOM URL:', inv)
await pb.goto(inv, { waitUntil: 'domcontentloaded' })
for (let i=0;i<10;i++) {
  await pb.waitForTimeout(3000)
  const t = (await pb.locator('body').innerText()).slice(0,120).replace(/\n/g,' | ')
  const ta = (await pa.locator('body').innerText()).slice(0,120).replace(/\n/g,' | ')
  console.log(`t=${(i+1)*3}s | A: ${ta.slice(0,60)} || B: ${t.slice(0,60)}`)
}
await pb.screenshot({ path: '/tmp/pc-B2.png' })
await pa.screenshot({ path: '/tmp/pc-A2.png' })
await b.close()
