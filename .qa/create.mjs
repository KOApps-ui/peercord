import { chromium } from 'playwright'
const b = await chromium.launch()
const p = await b.newPage({ viewport: { width: 1440, height: 900 } })
p.on('console', m => console.log(m.type().toUpperCase()+':', m.text().slice(0,200)))
p.on('pageerror', e => console.log('PE:', e.message))
await p.goto('http://localhost:5180/', { waitUntil: 'domcontentloaded' })
await p.waitForTimeout(1200)
await p.getByRole('button', { name: 'Sunucu Oluştur' }).first().click()
await p.waitForTimeout(600)
const d = p.locator('[role="dialog"]')
await d.getByLabel('Sunucu adı').fill('Debug Odası')
await p.waitForTimeout(600)
console.log('BTN:', await d.getByRole('button').allInnerTexts())
await d.getByRole('button', { name: 'Sunucu Oluştur' }).click()
await p.waitForTimeout(6000)
const st = await p.evaluate(() => { const s = window.__pc?.useAppStore?.getState?.(); return s ? { ready:s.ready, guild:s.guild?.name, room:s.roomId, err:s.error, modal:s.modal, toasts:s.toasts.map(t=>t.title+': '+(t.description||'')) } : 'no' })
console.log('STATE:', JSON.stringify(st))
await p.screenshot({ path: '/tmp/pc-created.png' })
await b.close()
