import { chromium } from 'playwright';
const b = await chromium.launch({ headless: true });
const p = await b.newPage();
await p.setViewportSize({ width: 1440, height: 900 });
p.on('console', m => console.log('CONSOLE', m.type(), m.text().slice(0,150)));
p.on('pageerror', e => console.log('PAGEERR', e.message));
await p.goto('http://localhost:5180/', { waitUntil: 'networkidle' });
await p.waitForTimeout(500);
console.log('BODY1:', (await p.locator('body').innerText()).slice(0,300).replace(/\n/g,' | '));
await p.getByRole('button', { name: /Sunucu Olu\u015ftur/i }).first().click();
await p.waitForTimeout(300);
await p.getByLabel(/Sunucu ad/i).fill('Debug Odasi');
await p.getByRole('button', { name: /Sunucu Olu\u015ftur/i }).click();
await p.waitForTimeout(8000);
console.log('URL:', p.url());
console.log('BODY2:', (await p.locator('body').innerText()).slice(0,600).replace(/\n/g,' | '));
console.log('UYELER count:', await p.locator('text=/\u00DCyeler/').count());
await p.screenshot({ path: '/tmp/pc-dbg.png', fullPage: true });
await b.close();
