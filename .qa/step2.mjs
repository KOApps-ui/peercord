import { chromium } from 'playwright'
const b = await chromium.launch()
const p = await b.newPage({ viewport: { width: 1440, height: 900 } })
await p.goto('http://localhost:5180/', { waitUntil: 'domcontentloaded' })
await p.waitForTimeout(1200)
await p.getByRole('button', { name: 'Sunucu Oluştur' }).first().click()
await p.waitForTimeout(600)
const inp = p.getByLabel('Sunucu adı')
await inp.click()
await inp.pressSequentially('Debug Odası', { delay: 20 })
await p.waitForTimeout(500)
console.log('INPUT VALUE:', await inp.inputValue())
const modalBtns = await p.locator('[role="dialog"] button, [data-radix-popper-content-wrapper] button').allInnerTexts()
console.log('DIALOG BUTTONS:', JSON.stringify(modalBtns))
await p.screenshot({ path: '/tmp/pc-step2b.png' })
await b.close()
