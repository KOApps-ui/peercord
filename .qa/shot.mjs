import { chromium } from 'playwright'
const b = await chromium.launch()
const A = await b.newContext({ viewport: { width: 1440, height: 900 } })
const B = await b.newContext({ viewport: { width: 1440, height: 900 } })
const pa = await A.newPage(); const pb = await B.newPage()
await pa.goto('http://localhost:5180/', { waitUntil: 'domcontentloaded' }); await pa.waitForTimeout(1000)
await pa.getByRole('button', { name: 'Sunucu Oluştur' }).first().click(); await pa.waitForTimeout(400)
const d = pa.locator('[role="dialog"]')
await d.getByLabel('Sunucu adı').fill('Gece Kulübü'); await pa.waitForTimeout(400)
await d.getByRole('button', { name: 'Sunucu Oluştur' }).click(); await pa.waitForTimeout(2500)
const url = await pa.evaluate(() => location.href)
await pb.goto(url, { waitUntil: 'domcontentloaded' }); await pb.waitForTimeout(4500)
const comp = pa.locator('textarea').first()
await comp.click(); await comp.fill('Selam! Bu mesaj P2P olarak gidiyor 🚀'); await pa.keyboard.press('Enter')
await pa.waitForTimeout(2000)
const compB = pb.locator('textarea').first()
await compB.click(); await compB.fill('B tarafından cevap ✅'); await pb.keyboard.press('Enter')
await pa.waitForTimeout(2500)
console.log('A text:', (await pa.locator('main').innerText()).replace(/\n/g,' | ').slice(0,400))
console.log('B text:', (await pb.locator('main').innerText()).replace(/\n/g,' | ').slice(0,400))
await pa.screenshot({ path: '/tmp/pc-v2-A.png' })
await pb.screenshot({ path: '/tmp/pc-v2-B.png' })
await b.close()
