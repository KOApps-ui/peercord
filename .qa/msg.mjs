import { chromium } from 'playwright'
const b = await chromium.launch()
const A = await b.newContext({ viewport: { width: 1440, height: 900 } })
const B = await b.newContext({ viewport: { width: 1440, height: 900 } })
const pa = await A.newPage(); const pb = await B.newPage()
const errs = []
for (const [n,p] of [['A',pa],['B',pb]]) {
  p.on('pageerror', e => errs.push(n+': '+e.message))
}
await pa.goto('http://localhost:5180/', { waitUntil: 'domcontentloaded' })
await pa.waitForTimeout(1000)
await pa.getByRole('button', { name: 'Sunucu Oluştur' }).first().click()
await pa.waitForTimeout(400)
const d = pa.locator('[role="dialog"]')
await d.getByLabel('Sunucu adı').fill('Gece Kulübü')
await pa.waitForTimeout(400)
await d.getByRole('button', { name: 'Sunucu Oluştur' }).click()
await pa.waitForTimeout(2500)
const url = await pa.evaluate(() => location.href)
await pb.goto(url, { waitUntil: 'domcontentloaded' })
await pb.waitForTimeout(4000)
// A mesaj gönder
const compA = pa.locator('textarea').first()
await compA.click()
await compA.fill('Selam! Bu mesaj P2P olarak gidiyor 🚀')
await compA.press('Enter')
await pa.waitForTimeout(3000)
const bodyA = await pa.locator('body').innerText()
const bodyB = await pb.locator('body').innerText()
console.log('A mesaj var mı:', bodyA.includes('P2P olarak gidiyor') || bodyA.includes('Selam!'))
console.log('B mesaj var mı:', bodyB.includes('P2P olarak gidiyor') || bodyB.includes('Selam!'))
// B cevap
const compB = pb.locator('textarea').first()
await compB.click(); await compB.fill('B tarafından cevap ✅'); await compB.press('Enter')
await pa.waitForTimeout(3000)
const newBodyA = await pa.locator('body').innerText()
console.log('A cevabı gördü:', newBodyA.includes('B tarafından cevap'))
const st = async (p) => p.evaluate(() => { const s = window.__pc?.useAppStore?.getState?.(); return { m: Object.values(s.messages).reduce((a,b)=>a+b.length,0), peers: s.peers.length, members: Object.keys(s.members).length } })
console.log('A state:', JSON.stringify(await st(pa)))
console.log('B state:', JSON.stringify(await st(pb)))
// Final validation
const aState = await st(pa)
const bState = await st(pb)
console.log('MESSAGES_WORK:', aState.m > 0 && bState.m > 0)
console.log('MEMBERS_COUNT:', aState.members === 2 && bState.members === 2)
console.log('PEERS_COUNT:', aState.peers === 1 && bState.peers === 1)
await pa.screenshot({ path: '/tmp/pc-final-A.png' })
await pb.screenshot({ path: '/tmp/pc-final-B.png' })
console.log('ERRS:', JSON.stringify(errs.slice(0,6), null, 1))
await b.close()